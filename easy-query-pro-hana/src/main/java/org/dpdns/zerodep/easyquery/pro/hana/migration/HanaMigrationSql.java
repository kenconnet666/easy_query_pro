package org.dpdns.zerodep.easyquery.pro.hana.migration;

import com.easy.query.core.migration.data.ColumnMigrationData;
import com.easy.query.core.migration.data.ForeignKeyMigrationData;
import com.easy.query.core.migration.data.TableMigrationData;
import org.dpdns.zerodep.easyquery.pro.hana.config.HanaSQLKeyword;

import java.math.BigDecimal;
import java.util.Arrays;
import java.util.Locale;
import java.util.Map;
import java.util.LinkedHashMap;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import com.easy.query.core.util.EasyStringUtil;
import java.util.regex.Matcher;

final class HanaMigrationSql {
    private static final HanaSQLKeyword KEYWORD = new HanaSQLKeyword();
    private static final Pattern STRING_LITERAL = Pattern.compile("N?'((?:[^']|'')*)'", Pattern.CASE_INSENSITIVE | Pattern.DOTALL);
    private static final Pattern ACTION = Pattern.compile("ON (UPDATE|DELETE) (CASCADE|RESTRICT|SET NULL|SET DEFAULT)");

    private HanaMigrationSql() {
    }

    static String name(String name) {
        return KEYWORD.getQuoteName(name);
    }

    static String raw(String name) {
        return name == null || EasyStringUtil.isBlank(name) ? null : KEYWORD.unquoteName(name);
    }

    static String qualified(String schema, String object) {
        return schema == null || EasyStringUtil.isBlank(schema) ? name(object) : name(schema) + "." + name(object);
    }

    static String table(TableMigrationData table) {
        return qualified(table.getSchema(), table.getTableName());
    }

    static String literal(String text) {
        return text == null ? "NULL" : "'" + text.replace("'", "''") + "'";
    }

    static String columns(String[] columns) {
        if (columns.length == 0) throw new IllegalArgumentException("HANA key/index columns must not be empty");
        return Arrays.stream(columns).map(HanaMigrationSql::name).collect(Collectors.joining(", "));
    }

    static String column(ColumnMigrationData column, boolean creating) {
        HanaColumnType type = HanaColumnType.parse(column.getDbType());
        String sql = name(column.getName()) + " " + type.sql();
        if (column.isGeneratedKey()) {
            if (!type.acceptsIdentity())
                throw new IllegalArgumentException("HANA identity requires an integer type: " + column.getName());
            if (creating) sql += " GENERATED BY DEFAULT AS IDENTITY";
        } else {
            String value = column.getDefValue();
            if (value != null && !EasyStringUtil.isBlank(value)) sql += " DEFAULT " + value;
            else if (!creating) sql += " DEFAULT NULL";
        }
        return sql + (column.isNotNull() || column.isPrimary() ? " NOT NULL" : " NULL");
    }

    static String targetSchema(TableMigrationData table, ForeignKeyMigrationData key) {
        return key instanceof HanaForeignKeyMigrationData ? ((HanaForeignKeyMigrationData) key).getTargetSchema() : table.getSchema();
    }

    static Map<String, String> actions(String sql) {
        LinkedHashMap<String, String> actions = new LinkedHashMap<String, String>();
        if (sql == null || EasyStringUtil.isBlank(sql)) return actions;
        String remaining = sql.trim().toUpperCase(Locale.ROOT).replaceAll("\\s+", " ");
        while (!remaining.isEmpty()) {
            Matcher matcher = ACTION.matcher(remaining);
            if (!matcher.lookingAt() || actions.putIfAbsent(matcher.group(1), matcher.group(2)) != null) {
                throw new IllegalArgumentException("Invalid HANA foreign key action: " + sql);
            }
            remaining = remaining.substring(matcher.end()).replaceFirst("^\\s+", "");
        }
        return actions;
    }

    static String actionSql(String sql) {
        return actions(sql).entrySet().stream().map(entry -> " ON " + entry.getKey() + " " + entry.getValue()).collect(Collectors.joining());
    }

    static boolean defaultMatches(HanaColumnType type, String sql, String catalogValue) {
        if (sql == null || EasyStringUtil.isBlank(sql) || sql.equalsIgnoreCase("NULL")) return catalogValue == null;
        if (type.name().equals("BOOLEAN")) {
            if (sql.equalsIgnoreCase("FALSE")) return "0".equals(catalogValue);
            if (sql.equalsIgnoreCase("TRUE")) return "1".equals(catalogValue);
        }
        Matcher literal = STRING_LITERAL.matcher(sql.trim());
        // SYS.TABLE_COLUMNS 已解码字符串；不能直接与带引号的注解文本比较。
        if (literal.matches()) return literal.group(1).replace("''", "'").equals(catalogValue);
        if (catalogValue == null) return false;
        try {
            return new BigDecimal(sql.trim()).compareTo(new BigDecimal(catalogValue)) == 0;
        } catch (NumberFormatException ignored) {
            return sql.trim().equalsIgnoreCase(catalogValue);
        }
    }
}

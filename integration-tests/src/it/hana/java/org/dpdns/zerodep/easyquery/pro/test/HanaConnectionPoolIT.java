package org.dpdns.zerodep.easyquery.pro.test;

import com.easy.query.api.proxy.client.DefaultEasyEntityQuery;
import com.easy.query.core.bootstrapper.EasyQueryBootstrapper;
import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import org.dpdns.zerodep.easyquery.pro.hana.config.HanaDatabaseConfiguration;
import org.dpdns.zerodep.easyquery.pro.test.entity.GeneratedProduct;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

import static org.junit.jupiter.api.Assertions.*;

class HanaConnectionPoolIT {
    @Test
    void concurrentTransactionsKeepKeysOnTheirOwnSessionsAndReleasePoolConnections() throws Exception {
        String table = HanaTestDatabase.uniqueName("POOL_IDENTITY");
        var config = new HikariConfig();
        config.setDataSource(HanaTestDatabase.dataSource());
        config.setPoolName(table);
        config.setMaximumPoolSize(2);
        config.setMinimumIdle(0);
        config.setConnectionTimeout(10_000);
        try (var setup = HanaTestDatabase.connect(); var statement = setup.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255) NOT NULL)");
            try (var pool = new HikariDataSource(config)) {
                var client = EasyQueryBootstrapper.defaultBuilderConfiguration().setDefaultDataSource(pool)
                        .useDatabaseConfigure(new HanaDatabaseConfiguration()).build();
                var query = new DefaultEasyEntityQuery(client);
                var executor = Executors.newFixedThreadPool(4);
                try {
                    var start = new CountDownLatch(1);
                    var tasks = new ArrayList<Future<WriteResult>>();
                    for (int worker = 0; worker < 4; worker++) {
                        int number = worker;
                        tasks.add(executor.submit(() -> {
                            assertTrue(start.await(10, TimeUnit.SECONDS));
                            var products = IntStream.range(0, 6).mapToObj(i -> new GeneratedProduct(number + ":" + i)).toList();
                            boolean commit = number != 3;
                            try (var transaction = client.beginTransaction()) {
                                assertEquals(products.size(), query.insertable(products).asTable(t -> table).batch(true).executeRows(true));
                                for (var product : products) assertNotNull(product.getId());
                                if (commit) transaction.commit();
                                else transaction.rollback();
                            }
                            return new WriteResult(products, commit);
                        }));
                    }
                    start.countDown();
                    var results = new ArrayList<WriteResult>();
                    for (var task : tasks) results.add(task.get(30, TimeUnit.SECONDS));
                    assertEquals(24L, results.stream().flatMap(r -> r.inserted().stream()).map(GeneratedProduct::getId).distinct().count());
                    var expected = results.stream().filter(WriteResult::committed).flatMap(r -> r.inserted().stream())
                            .collect(Collectors.toMap(GeneratedProduct::getId, GeneratedProduct::getName));
                    var actual = query.queryable(GeneratedProduct.class).asTable(t -> table).toList().stream()
                            .collect(Collectors.toMap(GeneratedProduct::getId, GeneratedProduct::getName));
                    assertEquals(18, actual.size());
                    assertEquals(expected, actual);
                    try (var recycled = pool.getConnection()) {
                        assertTrue(recycled.getAutoCommit());
                        assertFalse(recycled.isReadOnly());
                    }
                    assertEquals(0, pool.getHikariPoolMXBean().getActiveConnections());
                    assertTrue(pool.getHikariPoolMXBean().getTotalConnections() <= 2);
                } finally {
                    executor.shutdownNow();
                    assertTrue(executor.awaitTermination(10, TimeUnit.SECONDS));
                }
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }

    private record WriteResult(List<GeneratedProduct> inserted, boolean committed) {
    }
}

package org.dpdns.zerodep.easyquery.pro.test;

import com.easy.query.api.proxy.client.DefaultEasyEntityQuery;
import com.easy.query.core.bootstrapper.EasyQueryBootstrapper;
import org.dpdns.zerodep.easyquery.pro.hana.config.HanaDatabaseConfiguration;
import org.dpdns.zerodep.easyquery.pro.test.entity.GeneratedProduct;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.stream.Collectors;
import java.util.stream.IntStream;
import java.sql.Connection;
import java.sql.Statement;
import com.zaxxer.hikari.HikariDataSource;
import com.easy.query.core.api.client.EasyQueryClient;
import java.util.concurrent.ExecutorService;
import com.easy.query.core.basic.jdbc.tx.Transaction;
import java.util.Map;
import java.util.Objects;

import static org.junit.jupiter.api.Assertions.*;

class HanaConnectionPoolIT {
    @Test
    void concurrentTransactionsKeepKeysOnTheirOwnSessionsAndReleasePoolConnections() throws Exception {
        String table = HanaTestDatabase.uniqueName("POOL_IDENTITY");
        try (Connection setup = HanaTestDatabase.connect(); Statement statement = setup.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255) NOT NULL)");
            try (HikariDataSource pool = HanaTestDatabase.pool(2)) {
                EasyQueryClient client = EasyQueryBootstrapper.defaultBuilderConfiguration().setDefaultDataSource(pool)
                        .useDatabaseConfigure(new HanaDatabaseConfiguration()).build();
                DefaultEasyEntityQuery query = new DefaultEasyEntityQuery(client);
                ExecutorService executor = Executors.newFixedThreadPool(4);
                try {
                    CountDownLatch start = new CountDownLatch(1);
                    ArrayList<Future<HanaConnectionPoolIT.WriteResult>> tasks = new ArrayList<Future<WriteResult>>();
                    for (int worker = 0; worker < 4; worker++) {
                        int number = worker;
                        tasks.add(executor.submit(() -> {
                            assertTrue(start.await(10, TimeUnit.SECONDS));
                            List<GeneratedProduct> products = IntStream.range(0, 6).mapToObj(i -> new GeneratedProduct(number + ":" + i)).collect(Collectors.toList());
                            boolean commit = number != 3;
                            try (Transaction transaction = client.beginTransaction()) {
                                assertEquals(products.size(), query.insertable(products).asTable(t -> table).batch(true).executeRows(true));
                                for (GeneratedProduct product : products) assertNotNull(product.getId());
                                if (commit) transaction.commit();
                                else transaction.rollback();
                            }
                            return new WriteResult(products, commit);
                        }));
                    }
                    start.countDown();
                    ArrayList<HanaConnectionPoolIT.WriteResult> results = new ArrayList<WriteResult>();
                    for (Future<HanaConnectionPoolIT.WriteResult> task : tasks) results.add(task.get(30, TimeUnit.SECONDS));
                    assertEquals(24L, results.stream().flatMap(r -> r.inserted().stream()).map(GeneratedProduct::getId).distinct().count());
                    Map<Long, String> expected = results.stream().filter(WriteResult::committed).flatMap(r -> r.inserted().stream())
                            .collect(Collectors.toMap(GeneratedProduct::getId, GeneratedProduct::getName));
                    Map<Long, String> actual = query.queryable(GeneratedProduct.class).asTable(t -> table).toList().stream()
                            .collect(Collectors.toMap(GeneratedProduct::getId, GeneratedProduct::getName));
                    assertEquals(18, actual.size());
                    assertEquals(expected, actual);
                    try (Connection recycled = pool.getConnection()) {
                        assertTrue(recycled.getAutoCommit());
                        assertFalse(recycled.isReadOnly());
                    }
                    assertEquals(0, pool.getHikariPoolMXBean().getActiveConnections());
                    assertTrue(pool.getHikariPoolMXBean().getTotalConnections() <= 2);
                } finally {
                    executor.shutdownNow();
                    assertTrue(executor.awaitTermination(10, TimeUnit.SECONDS));
                }
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }

    private static final class WriteResult {
        private final List<GeneratedProduct> inserted;
        private final boolean committed;

        private WriteResult(List<GeneratedProduct> inserted, boolean committed) {
            this.inserted = inserted;
            this.committed = committed;
        }

        public List<GeneratedProduct> inserted() {
            return inserted;
        }

        public boolean committed() {
            return committed;
        }

        @Override
        public boolean equals(Object o) {
            if (this == o) return true;
            if (!(o instanceof WriteResult)) return false;
            WriteResult other = (WriteResult) o;
            return Objects.equals(inserted, other.inserted)
                    && committed == other.committed;
        }

        @Override
        public int hashCode() {
            return Objects.hash(inserted, committed);
        }

        @Override
        public String toString() {
            return "WriteResult[inserted=" + inserted + ", committed=" + committed + "]";
        }
    }
}

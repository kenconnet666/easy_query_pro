import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class HanaIdentityIT {
    @Test
    void driverRequiresSessionKeyRetrievalInsteadOfJdbcGeneratedKeys() throws SQLException {
        String table = '"' + HanaTestDatabase.uniqueName("JDBC_IDENTITY") + '"';
        try (Connection connection = HanaTestDatabase.connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE COLUMN TABLE " + table + " (id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                    + " PRIMARY KEY, name NVARCHAR(255))");
            String sql = "INSERT INTO " + table + " (name) VALUES (?)";
            try (PreparedStatement insert = connection.prepareStatement(sql)) {
                assertThrows(SQLException.class, () -> connection.prepareStatement(sql, new String[]{"ID"}));
                assertThrows(SQLException.class, () -> connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS));
                for (int i = 0; i < 3; i++) {
                    insert.setString(1, "row-" + i);
                    assertEquals(1, insert.executeUpdate());
                    try (ResultSet result = statement.executeQuery("SELECT CURRENT_IDENTITY_VALUE() FROM DUMMY")) {
                        assertTrue(result.next());
                        assertEquals(i + 1L, result.getLong(1));
                    }
                }
            } finally {
                statement.execute("DROP TABLE " + table);
            }
        }
    }

    @Test
    void upstreamJdbcExecutorBackfillsSingleAndBatchIdentityKeys() throws SQLException {
        String table = HanaTestDatabase.uniqueName("IDENTITY");
        DataSource dataSource = HanaTestDatabase.dataSource();
        EasyQueryClient client = EasyQueryBootstrapper.defaultBuilderConfiguration()
                .setDefaultDataSource(dataSource)
                .useDatabaseConfigure(new HanaDatabaseConfiguration())
                .build();
        DefaultEasyEntityQuery query = new DefaultEasyEntityQuery(client);
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY"
                    + " PRIMARY KEY, \"name\" NVARCHAR(255) NOT NULL)");
            try {
                GeneratedProduct single = new GeneratedProduct("single 中文");
                assertEquals(1L, query.insertable(single).asTable(t -> table).executeRows(true));
                assertNotNull(single.getId());
                assertTrue(single.getId() > 0);

                // A large input must retain key-to-entity order even when key retrieval is serial.
                List<GeneratedProduct> batch = IntStream.range(0, 1003)
                        .mapToObj(i -> new GeneratedProduct("batch-" + i)).collect(Collectors.toList());
                assertEquals(batch.size(), query.insertable(batch).asTable(t -> table).batch(true).executeRows(true));
                for (GeneratedProduct product : batch) assertNotNull(product.getId(), product.getName());
                assertEquals(batch.size(), batch.stream().map(GeneratedProduct::getId).distinct().count());

                List<GeneratedProduct> persisted = query.queryable(GeneratedProduct.class).asTable(t -> table)
                        .orderBy(p -> p.id().asc()).toList();
                assertEquals(single.getName(), persisted.get(0).getName());
                assertEquals(single.getId(), persisted.get(0).getId());
                assertEquals(batch.size() + 1, persisted.size());
                for (int i = 0; i < batch.size(); i++) {
                    assertEquals(batch.get(i).getId(), persisted.get(i + 1).getId());
                    assertEquals(batch.get(i).getName(), persisted.get(i + 1).getName());
                }
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }
}

    @Test
    void afterCallbacksSeeFilledKeysAndCannotReplaceThemWithNestedIdentityValues() throws SQLException {
        String table = HanaTestDatabase.uniqueName("KEY_CALLBACK");
        String audit = HanaTestDatabase.uniqueName("KEY_AUDIT");
        GeneratedProduct product = new GeneratedProduct("outer");
        class Listener implements JdbcExecutorListener {
            private DefaultEasyEntityQuery query;
            private Long observedKey;
            private int internalKeyReads;
            private boolean insertedAudit;

            @Override
            public boolean enable() {
                return true;
            }

            @Override
            public void onExecuteBefore(JdbcExecuteBeforeArg arg) {
                if (arg.getSql().contains("CURRENT_IDENTITY_VALUE()")) internalKeyReads++;
            }

            @Override
            public void onExecuteAfter(JdbcExecuteAfterArg arg) {
                if (!insertedAudit && arg.getBeforeArg().getSql().startsWith("INSERT INTO \"" + table + "\"")) {
                    insertedAudit = true;
                    observedKey = product.getId();
                    query.insertable(new GeneratedProduct("nested")).asTable(t -> audit).executeRows(false);
                }
            }
        }
        Listener listener = new Listener();
        EasyQueryClient client = EasyQueryBootstrapper.defaultBuilderConfiguration()
                .setDefaultDataSource(HanaTestDatabase.dataSource())
                .useDatabaseConfigure(new HanaDatabaseConfiguration())
                .replaceService(JdbcExecutorListener.class, listener).build();
        listener.query = new DefaultEasyEntityQuery(client);
        try (Connection connection = HanaTestDatabase.connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255))");
            try {
                statement.execute("CREATE COLUMN TABLE \"" + audit + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, \"name\" NVARCHAR(255))");
                try {
                    try (Transaction transaction = client.beginTransaction()) {
                        assertEquals(1L, listener.query.insertable(product).asTable(t -> table).executeRows(true));
                        GeneratedProduct persisted = listener.query.queryable(GeneratedProduct.class).asTable(t -> table).singleNotNull();
                        assertTrue(listener.insertedAudit);
                        assertEquals(persisted.getId(), product.getId());
                        assertEquals(product.getId(), listener.observedKey);
                        assertEquals(0, listener.internalKeyReads);
                        assertEquals(1L, listener.query.queryable(GeneratedProduct.class).asTable(t -> audit).count());
                        transaction.rollback();
                    }
                    assertEquals(0L, listener.query.queryable(GeneratedProduct.class).asTable(t -> table).count());
                    assertEquals(0L, listener.query.queryable(GeneratedProduct.class).asTable(t -> audit).count());
                } finally {
                    statement.execute("DROP TABLE \"" + audit + "\"");
                }
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }

    @Test
    void failedBatchReportsCompletedRowsAndPreservesTheDatabaseFailure() throws SQLException {
        String table = HanaTestDatabase.uniqueName("KEY_FAILURE");
        IllegalStateException callbackFailure = new IllegalStateException("after callback failed");
        class Listener implements JdbcExecutorListener {
            private JdbcExecuteAfterArg observed;

            @Override
            public boolean enable() {
                return true;
            }

            @Override
            public void onExecuteBefore(JdbcExecuteBeforeArg arg) {
            }

            @Override
            public void onExecuteAfter(JdbcExecuteAfterArg arg) {
                if (arg.getBeforeArg().getSql().startsWith("INSERT INTO \"" + table + "\"")) {
                    observed = arg;
                    if (arg.getException() != null) throw callbackFailure;
                }
            }
        }
        Listener listener = new Listener();
        EasyQueryClient client = EasyQueryBootstrapper.defaultBuilderConfiguration()
                .setDefaultDataSource(HanaTestDatabase.dataSource())
                .useDatabaseConfigure(new HanaDatabaseConfiguration())
                .replaceService(JdbcExecutorListener.class, listener).build();
        DefaultEasyEntityQuery query = new DefaultEasyEntityQuery(client);
        try (Connection connection = HanaTestDatabase.connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255) NOT NULL, CHECK (\"name\" <> 'bad'))");
            try {
                try (Transaction transaction = client.beginTransaction()) {
                    GeneratedProduct good = new GeneratedProduct("valid");
                    GeneratedProduct bad = new GeneratedProduct("bad");
                    RuntimeException thrown = assertThrows(RuntimeException.class, () -> query.insertable(Arrays.asList(good, bad))
                            .asTable(t -> table).batch(true).executeRows(true));
                    assertNotSame(callbackFailure, thrown);
                    assertNotNull(good.getId());
                    assertNull(bad.getId());
                    assertEquals(1, listener.observed.getRows());
                    assertEquals(2, listener.observed.getBeforeArg().getSqlParameters().size());
                    assertInstanceOf(SQLException.class, listener.observed.getException());
                    assertEquals(Arrays.asList(callbackFailure), Arrays.asList(listener.observed.getException().getSuppressed()));
                    transaction.rollback();
                }
                assertEquals(0L, query.queryable(GeneratedProduct.class).asTable(t -> table).count());
                GeneratedProduct recovered = new GeneratedProduct("recovered");
                assertEquals(1L, query.insertable(recovered).asTable(t -> table).executeRows(true));
                assertNotNull(recovered.getId());
                assertNull(listener.observed.getException());
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }

    @Test
    void triggerSideWritesAreRejectedBeforeUnsafeBackfillButRemainAvailableWithoutBackfill() throws SQLException {
        String table = HanaTestDatabase.uniqueName("KEY_TRIGGER");
        String audit = HanaTestDatabase.uniqueName("KEY_TRIGGER_AUDIT");
        String trigger = HanaTestDatabase.uniqueName("KEY_TRIGGER_HOOK");
        DefaultEasyEntityQuery query = HanaTestDatabase.client();
        try (Connection connection = HanaTestDatabase.connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255))");
            try {
                statement.execute("CREATE COLUMN TABLE \"" + audit + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, \"name\" NVARCHAR(255))");
                try {
                    statement.execute("CREATE TRIGGER \"" + trigger + "\" AFTER INSERT ON \"" + table
                            + "\" REFERENCING NEW ROW inserted FOR EACH ROW BEGIN INSERT INTO \"" + audit
                            + "\" (\"name\") VALUES (:inserted.\"name\"); END");
                    try {
                        List<GeneratedProduct> products = Arrays.asList(new GeneratedProduct("one"), new GeneratedProduct("two"));
                        assertThrows(RuntimeException.class, () -> query.insertable(products).asTable(t -> table).batch(true).executeRows(true));
                        assertEquals(0L, query.queryable(GeneratedProduct.class).asTable(t -> table).count());
                        assertEquals(0L, query.queryable(GeneratedProduct.class).asTable(t -> audit).count());
                        for (GeneratedProduct product : products) assertNull(product.getId());
                        assertEquals(2L, query.insertable(products).asTable(t -> table).batch(true).executeRows(false));
                        assertEquals(Arrays.asList(1L, 2L), query.queryable(GeneratedProduct.class).asTable(t -> table)
                                .orderBy(p -> p.id().asc()).selectColumn(p -> p.id()).toList());
                        assertEquals(Arrays.asList(100L, 101L), query.queryable(GeneratedProduct.class).asTable(t -> audit)
                                .orderBy(p -> p.id().asc()).selectColumn(p -> p.id()).toList());
                    } finally {
                        statement.execute("DROP TRIGGER \"" + trigger + "\"");
                    }
                } finally {
                    statement.execute("DROP TABLE \"" + audit + "\"");
                }
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }

    @Test
    void nonAdminCrossSchemaWritesRespectTriggerChecksAndQuotedTargets() throws SQLException {
        String trigger = HanaTestDatabase.uniqueName("KEY_PRIVILEGES_HOOK");
        try (HanaTestDatabase.TestUser user = HanaTestDatabase.createUser("KEY_USER");
             HanaTestDatabase.TestTable target = HanaTestDatabase.createTable("KEY_PRIVILEGES", "\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255)");
             HanaTestDatabase.TestTable audit = HanaTestDatabase.createTable("KEY_PRIVILEGES_AUDIT", "\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, \"name\" NVARCHAR(255)");
             Statement statement = target.connection().createStatement()) {
            String table = target.name();
            statement.execute("GRANT SELECT, INSERT ON \"" + table + "\" TO " + user.name());
            DefaultEasyEntityQuery query = HanaTestDatabase.client(user.dataSource());
            GeneratedProduct first = new GeneratedProduct("first");
            assertEquals(1L, query.insertable(first).asTable(t -> '"' + table + '"')
                    .asSchema(s -> "\"SYSTEM\"").executeRows(true));
            assertEquals(1L, first.getId());
            statement.execute("CREATE TRIGGER \"" + trigger + "\" AFTER INSERT ON \"" + table
                    + "\" REFERENCING NEW ROW inserted FOR EACH ROW BEGIN INSERT INTO \"" + audit.name()
                    + "\" (\"name\") VALUES (:inserted.\"name\"); END");
            try {
                GeneratedProduct rejected = new GeneratedProduct("rejected");
                assertThrows(RuntimeException.class, () -> query.insertable(rejected)
                        .asTable(t -> '"' + table + '"').asSchema(s -> "\"SYSTEM\"").executeRows(true));
                assertNull(rejected.getId());
                assertEquals(1L, query.queryable(GeneratedProduct.class).asTable(t -> table).asSchema(s -> "SYSTEM").count());
            } finally {
                statement.execute("DROP TRIGGER \"" + trigger + "\"");
            }
            GeneratedProduct afterDrop = new GeneratedProduct("after-drop");
            assertEquals(1L, query.insertable(afterDrop).asTable(t -> table).asSchema(s -> "SYSTEM").executeRows(true));
            assertEquals(2L, afterDrop.getId());
        }
    }

    @Test
    void synonymTargetsCannotBypassBaseTableValidation() throws SQLException {
        String table = HanaTestDatabase.uniqueName("KEY_BASE");
        String synonym = HanaTestDatabase.uniqueName("KEY_SYNONYM");
        DefaultEasyEntityQuery query = HanaTestDatabase.client();
        try (Connection connection = HanaTestDatabase.connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE COLUMN TABLE \"" + table + "\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(255))");
            try {
                statement.execute("CREATE SYNONYM \"" + synonym + "\" FOR \"" + table + "\"");
                try {
                    assertThrows(RuntimeException.class, () -> query.insertable(new GeneratedProduct("rejected"))
                            .asTable(t -> synonym).executeRows(true));
                    assertEquals(0L, query.queryable(GeneratedProduct.class).asTable(t -> table).count());
                    assertEquals(1L, query.insertable(new GeneratedProduct("accepted")).asTable(t -> synonym).executeRows(false));
                } finally {
                    statement.execute("DROP SYNONYM \"" + synonym + "\"");
                }
            } finally {
                statement.execute("DROP TABLE \"" + table + "\"");
            }
        }
    }

package org.dpdns.zerodep.easyquery.pro.test;

import com.easy.query.core.exception.EasyQuerySQLCommandException;
import org.dpdns.zerodep.easyquery.pro.hana.metadata.HanaCatalog;
import org.dpdns.zerodep.easyquery.pro.hana.metadata.HanaRelationMetadata;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.sql.Statement;
import java.util.Arrays;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.*;

class HanaCatalogIT {
    @Test
    void describesExactSchemasColumnsKeysIndexesCommentsAndViews() throws SQLException {
        HanaCatalog catalog = new HanaCatalog(HanaTestDatabase.dataSource());
        try (HanaTestDatabase.TestSchema first = HanaTestDatabase.createSchema("CATALOG"); HanaTestDatabase.TestSchema other = HanaTestDatabase.createSchema("CATALOG_OTHER");
             Statement statement = first.connection().createStatement()) {
            String parent = first.qualified("order");
            statement.execute("CREATE COLUMN TABLE " + parent + " (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY,"
                    + "\"code\" NVARCHAR(20) NOT NULL, \"display\" NVARCHAR(31) DEFAULT 'O''Reilly;中文',"
                    + "\"amount\" DECIMAL(17,3) NOT NULL DEFAULT 0.125, PRIMARY KEY (\"id\",\"code\"))");
            statement.execute("COMMENT ON TABLE " + parent + " IS 'parent''s;中文'");
            statement.execute("COMMENT ON COLUMN " + parent + ".\"display\" IS 'display''s;说明'");
            statement.execute("CREATE UNIQUE INDEX " + first.qualified("uq_display_amount") + " ON " + parent + " (\"display\",\"amount\")");
            statement.execute("CREATE COLUMN TABLE " + first.qualified("child") + " (\"parentId\" BIGINT,\"parentCode\" NVARCHAR(20),"
                    + "CONSTRAINT \"fk_parent\" FOREIGN KEY (\"parentId\",\"parentCode\") REFERENCES " + parent + " (\"id\",\"code\") ON DELETE CASCADE)");
            statement.execute("CREATE ROW TABLE " + first.qualified("row_table") + " (\"id\" INTEGER)");
            statement.execute("CREATE COLUMN TABLE " + first.qualified("odd\"table") + " (\"a\"\"b\" NVARCHAR(11))");
            statement.execute("CREATE VIEW " + first.qualified("visible") + " AS SELECT \"id\",\"display\" FROM " + parent);
            statement.execute("CREATE COLUMN TABLE " + other.qualified("order") + " (\"marker\" NVARCHAR(7))");

            assertTrue(catalog.schemas().contains(first.name()));
            assertEquals(5, catalog.relations(first.name()).size());
            HanaRelationMetadata table = catalog.describe(first.name(), "order").get();
            assertEquals(HanaRelationMetadata.Kind.TABLE, table.relation().kind());
            assertEquals("COLUMN", table.relation().storageType());
            assertEquals("parent's;中文", table.relation().comment());
            assertEquals(Arrays.asList("id", "code", "display", "amount"), table.columns().stream().map(HanaRelationMetadata.Column::name).collect(Collectors.toList()));
            assertEquals(Arrays.asList("id", "code"), table.primaryKeyColumns());
            HanaRelationMetadata.Column display = table.columns().get(2);
            assertEquals(31L, display.length());
            assertEquals(HanaRelationMetadata.Nullability.NULLABLE, display.nullability());
            assertEquals("display's;说明", display.comment());
            // HANA 目录保存解码后的字符串默认值，不包含 SQL 字面量外层引号。
            assertEquals("O'Reilly;中文", display.defaultValue());
            assertNotNull(table.columns().get(0).generationType());
            assertEquals(17L, table.columns().get(3).length());
            assertEquals(3, table.columns().get(3).scale());
            HanaRelationMetadata.Index index = table.indexes().stream().filter(i -> i.name().equals("uq_display_amount")).findFirst().get();
            assertTrue(index.unique());
            assertEquals(Arrays.asList("display", "amount"), index.columns().stream().map(HanaRelationMetadata.IndexColumn::name).collect(Collectors.toList()));
            HanaRelationMetadata.ForeignKey foreignKey = catalog.describe(first.name(), "child").get().foreignKeys().get(0);
            assertEquals(first.name(), foreignKey.referencedSchema());
            assertEquals("order", foreignKey.referencedTable());
            assertEquals("CASCADE", foreignKey.deleteRule());
            assertTrue(foreignKey.enforced());
            assertEquals(Arrays.asList("parentId", "parentCode"), foreignKey.columns().stream().map(HanaRelationMetadata.ReferenceColumn::name).collect(Collectors.toList()));
            assertEquals("ROW", catalog.find(first.name(), "row_table").get().storageType());
            HanaRelationMetadata view = catalog.describe(first.name(), "visible").get();
            assertEquals(HanaRelationMetadata.Kind.VIEW, view.relation().kind());
            assertEquals(Arrays.asList("id", "display"), view.columns().stream().map(HanaRelationMetadata.Column::name).collect(Collectors.toList()));
            assertEquals(Arrays.asList("marker"), catalog.describe(other.name(), "order").get().columns().stream().map(HanaRelationMetadata.Column::name).collect(Collectors.toList()));
            assertEquals("a\"b", catalog.describe(first.name(), "odd\"table").get().columns().get(0).name());
            assertThrows(UnsupportedOperationException.class, () -> table.columns().clear());
            assertTrue(!catalog.find(first.name(), "absent\"; DROP TABLE order;--").isPresent());
            assertTrue(catalog.find(first.name(), "order").isPresent());
        }
    }

    @Test
    void missingObjectsAndPermissionFailuresAreNotTheSameResult() throws SQLException {
        try (HanaTestDatabase.TestSchema schema = HanaTestDatabase.createSchema("CATALOG_PERMISSIONS"); HanaTestDatabase.TestUser user = HanaTestDatabase.createUser("CATALOG_USER");
             Statement statement = schema.connection().createStatement()) {
            statement.execute("CREATE COLUMN TABLE " + schema.qualified("allowed") + " (\"id\" INTEGER)");
            statement.execute("CREATE COLUMN TABLE " + schema.qualified("denied") + " (\"id\" INTEGER)");
            statement.execute("GRANT SELECT ON " + schema.qualified("allowed") + " TO " + user.name());
            HanaCatalog catalog = new HanaCatalog(user.dataSource());
            assertEquals(1, catalog.describe(schema.name(), "allowed").get().columns().size());
            EasyQuerySQLCommandException failure = assertThrows(EasyQuerySQLCommandException.class, () -> catalog.describe(schema.name(), "denied"));
            assertEquals(258, assertInstanceOf(SQLException.class, failure.getCause()).getErrorCode());
            assertTrue(!catalog.find(schema.name(), "not_present").isPresent());
        }
    }
}
